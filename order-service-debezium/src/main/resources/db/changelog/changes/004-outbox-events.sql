CREATE TABLE outbox_events (
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    aggregate_id VARCHAR(128) NOT NULL,
    partition_key VARCHAR(128) NOT NULL,
    event_type   VARCHAR(128) NOT NULL,
    payload      JSONB NOT NULL,
    trace_parent TEXT,
    PRIMARY KEY (created_at, id)
) PARTITION BY RANGE (created_at);

--changeset outbox:004-outbox-events-partitions splitStatements:false
DO $$
DECLARE
    from_month date := date_trunc('month', CURRENT_DATE)::date;
    months     int  := 12;
    i          int;
    part_from  timestamptz;
    part_to    timestamptz;
    part_name  text;
BEGIN
    FOR i IN 0..months - 1 LOOP
        part_from := from_month + make_interval(months => i);
        part_to   := from_month + make_interval(months => i + 1);
        part_name := 'outbox_events_' || to_char(part_from, 'YYYY_MM');
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS %I PARTITION OF outbox_events FOR VALUES FROM (%L) TO (%L)',
            part_name, part_from, part_to
        );
    END LOOP;
END $$;
